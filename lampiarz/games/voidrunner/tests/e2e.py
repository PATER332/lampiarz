"""VOIDRUNNER end-to-end checks in a real Chromium (Playwright).

Usage: python3 games/voidrunner/tests/e2e.py <base_url> <screenshot_dir>
(base_url = the EVGAMES server, e.g. http://localhost:4321)
"""
import json, sys, time
from playwright.sync_api import sync_playwright

base, out = sys.argv[1].rstrip('/'), sys.argv[2]
URL = base + '/g/voidrunner/'
results, errors = [], []


def check(name, ok, extra=''):
    results.append((name, bool(ok)))
    print(('PASS ' if ok else 'FAIL ') + name + (f' — {extra}' if extra and not ok else ''))


def ev(page, js):
    return page.evaluate(js)


with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1440, 'height': 810})
    page = ctx.new_page()
    page.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    page.on('console', lambda m: errors.append(f'console: {m.text}') if m.type == 'error' else None)
    page.goto(URL)
    page.evaluate('localStorage.clear()')
    page.reload()
    time.sleep(1.2)
    # ---------------------------------------------------------------- title
    labels = [t.strip().split('\n')[0] for t in page.locator('.title-screen .btn').all_inner_texts()]
    check('title menu: Nowa gra, Kontynuuj, Ulepszenia, Ustawienia, Sterowanie', [l.upper() for l in labels] == ['NOWA GRA', 'KONTYNUUJ', 'ULEPSZENIA', 'USTAWIENIA', 'STEROWANIE'], str(labels))
    check('Kontynuuj disabled without a save', page.locator('[data-act=continue]').is_disabled())
    page.screenshot(path=f'{out}/01-title.png')
    # ---------------------------------------------------------------- controls + rebinding
    page.click('[data-act=controls]')
    time.sleep(0.3)
    check('controls screen lists all actions', page.locator('.keys-table .kbd').count() >= 12)
    page.locator('.kbd[data-id=heal]').first.click()
    time.sleep(0.1)
    page.keyboard.press('KeyH')
    time.sleep(0.2)
    keys = ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).keys.heal")
    check('rebinding a key is saved', keys[0] == 'KeyH', str(keys))
    page.click('[data-act=defaultkeys]')
    time.sleep(0.2)
    check('restore default keys', ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).keys.heal[0]") == 'KeyQ')
    page.screenshot(path=f'{out}/02-controls.png')
    page.keyboard.press('Escape')
    time.sleep(0.3)
    # ---------------------------------------------------------------- settings
    page.click('[data-act=settings]')
    time.sleep(0.3)
    page.click('[data-act=toggle][data-id=shake]')
    time.sleep(0.2)
    check('settings: screen shake toggle saved', ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).settings.shake") is False)
    page.click('[data-act=toggle][data-id=shake]')
    page.locator('input[data-set=music]').fill('30')
    time.sleep(0.2)
    check('settings: music volume saved', abs(ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).settings.music") - 0.3) < 0.01)
    page.locator('input[data-set=ambient]').fill('60')
    time.sleep(0.2)
    check('settings: weather / ambience volume saved', abs(ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).settings.ambient") - 0.6) < 0.01)
    page.screenshot(path=f'{out}/03-settings.png')
    page.click('.btn.primary[data-act=close]')
    time.sleep(0.3)
    # ---------------------------------------------------------------- new game
    page.click('[data-act=new]')
    time.sleep(0.6)
    check('first expedition shows the Polish control guide', page.get_by_text('Zaczynamy').count() == 1)
    page.click('text=Zaczynamy')
    time.sleep(1.5)
    check('HUD visible during play', page.locator('.vr-hud:not(.hidden) .bar.hp').count() == 1)
    check('tutorial room in the first sector', ev(page, 'window.__voidrunner.game.room.template') == 'samouczek')
    check('area banner shows the sector name', 'Opuszczony Kompleks'.upper() in page.locator('.vr-hud').inner_text().upper())
    x0 = ev(page, 'window.__voidrunner.game.player.x')
    page.keyboard.down('KeyD')
    time.sleep(0.6)
    page.keyboard.up('KeyD')
    x1 = ev(page, 'window.__voidrunner.game.player.x')
    check('D moves the player right', x1 - x0 > 30, f'{x0}->{x1}')
    check('checkpoint activated → expedition saved', ev(page, "!!localStorage.getItem('voidrunner.run.v1')"))
    y0 = ev(page, 'window.__voidrunner.game.player.y')
    page.keyboard.down('Space')
    time.sleep(0.25)
    y1 = ev(page, 'window.__voidrunner.game.player.y')
    page.keyboard.up('Space')
    check('Space jumps', y0 - y1 > 20, f'{y0}->{y1}')
    check('game keys do not scroll the page', ev(page, 'window.scrollY') == 0)
    time.sleep(0.8)
    page.screenshot(path=f'{out}/04-play.png')
    # ---------------------------------------------------------------- combat
    ev(page, '() => { window.__voidrunner.game.enemies.length = 0; }')
    ev(page, """() => { const g = window.__voidrunner.game; const p = g.player;
      g.enemies.push(Object.assign({}, { id: 9999, type: 'hunter', elite: false, x: p.x + 20, y: p.y + p.h - 20, w: 14, h: 20, vx: 0, vy: 0, onGround: true, hitWall: 0, hitCeiling: false,
        hp: 40, maxHp: 40, facing: -1, state: 'recover', stateT: 0, cd: 9, flash: 0, stun: 0, dead: false, deathT: 0, homeX: p.x + 20, homeY: p.y, phase: 0, seed: 1, hurtful: 0, n: 0, m: 0 })); g.doorLocked = true; }""")
    for _ in range(8):
        page.keyboard.press('KeyJ')
        time.sleep(0.28)
    dead = ev(page, '!window.__voidrunner.game.enemies.some(e => e.id === 9999 && !e.dead)')
    check('J attacks defeat an enemy', dead)
    page.screenshot(path=f'{out}/05-combat.png')
    # charged attack (hold J)
    en0 = ev(page, 'window.__voidrunner.game.player.energy')
    page.keyboard.press('KeyK')
    time.sleep(0.3)
    check('K uses the special ability (energy spent)', ev(page, 'window.__voidrunner.game.player.energy') < en0)
    page.keyboard.down('KeyJ')
    time.sleep(0.75)
    page.keyboard.up('KeyJ')
    time.sleep(0.05)
    check('holding J releases a charged attack', ev(page, "(() => { const a = window.__voidrunner.game.player.attack; return !!a && a.kind === 'charged'; })()") or ev(page, "window.__voidrunner.game.particles.some(q => q.kind === 'ring')"))
    # R and mouse buttons
    time.sleep(0.6)
    page.keyboard.press('KeyR')
    time.sleep(0.05)
    check('R attacks', ev(page, "(() => { const a = window.__voidrunner.game.player.attack; return !!a && a.kind !== 'special'; })()"))
    time.sleep(0.6)
    box = page.locator('canvas.vr-game').bounding_box()
    page.mouse.click(box['x'] + box['width'] / 2, box['y'] + box['height'] / 2)
    time.sleep(0.05)
    check('left mouse button attacks', ev(page, "(() => { const a = window.__voidrunner.game.player.attack; return !!a && a.kind !== 'special'; })()"))
    time.sleep(0.6)
    ev(page, '() => { const p = window.__voidrunner.game.player; p.energy = p.maxEnergy; }')
    en1 = ev(page, 'window.__voidrunner.game.player.energy')
    page.mouse.click(box['x'] + box['width'] / 2, box['y'] + box['height'] / 2, button='right')
    time.sleep(0.3)
    check('right mouse button uses the special ability', ev(page, 'window.__voidrunner.game.player.energy') < en1)
    check('HUD shows the weather', 'POGODA:' in page.locator('.vr-hud').inner_text().upper())
    ev(page, "() => { const a = window.__voidrunner; a.game.weather = 'rain'; a.audio.setAmbience(a.game.run.area, 'rain', true); }")
    time.sleep(0.5)
    check('rain ambience is playing (Web Audio layers running)', ev(page, "(() => { const au = window.__voidrunner.audio; return !!au.ctx && au.ctx.state === 'running' && [...au.layers.values()].some(l => l.gain.gain.value > 0.01); })()"))
    check('minimap visible', page.locator('.minimap canvas').count() == 1 and page.locator('.minimap canvas').is_visible())
    # ---------------------------------------------------------------- pause menu
    page.keyboard.press('Escape')
    time.sleep(0.4)
    pl = [t.strip().split('\n')[0].upper() for t in page.locator('.panel .btn').all_inner_texts()]
    check('pause: Wznów, Ekwipunek, Ustawienia, Sterowanie, Uruchom ponownie, Powrót do menu', pl == ['WZNÓW', 'EKWIPUNEK', 'USTAWIENIA', 'STEROWANIE', 'URUCHOM PONOWNIE', 'POWRÓT DO MENU'], str(pl))
    t0 = ev(page, 'window.__voidrunner.game.time')
    time.sleep(0.4)
    check('game is frozen while paused', ev(page, 'window.__voidrunner.game.time') == t0)
    page.screenshot(path=f'{out}/06-pause.png')
    page.click('[data-act=inventory]')
    time.sleep(0.3)
    check('equipment screen from the pause menu', page.get_by_text('Ulepszenia wyprawy').count() == 1)
    page.screenshot(path=f'{out}/07-inventory.png')
    page.keyboard.press('Escape')
    time.sleep(0.3)
    check('closing equipment returns to pause', page.locator('[data-act=resume]').count() == 1)
    page.click('[data-act=resume]')
    time.sleep(0.4)
    check('Wznów resumes the game', ev(page, 'window.__voidrunner.game.time') > t0)
    page.keyboard.press('KeyI')
    time.sleep(0.3)
    check('I opens the equipment', page.get_by_text('Ulepszenia wyprawy').count() == 1)
    page.keyboard.press('KeyI')
    time.sleep(0.3)
    check('I closes it again', page.get_by_text('Ulepszenia wyprawy').count() == 0)
    # ---------------------------------------------------------------- upgrade choice
    ev(page, "window.__voidrunner.game.offerChoice(3, 'Ołtarz ulepszeń')")
    time.sleep(0.4)
    check('upgrade choice shows 3 cards', page.locator('.card').count() == 3)
    page.screenshot(path=f'{out}/08-choice.png')
    first = page.locator('.card').first.get_attribute('data-id')
    page.keyboard.press('Digit1')
    time.sleep(0.3)
    check('key 1 picks the first upgrade', ev(page, f"window.__voidrunner.game.up('{first}')") == 1)
    check('HUD shows the upgrade', page.locator('.ups span').count() == 1)
    # ---------------------------------------------------------------- restart from checkpoint
    page.keyboard.press('Escape')
    time.sleep(0.3)
    page.click('[data-act=restart]')
    time.sleep(0.8)
    check('Uruchom ponownie restarts from the save point', ev(page, 'window.__voidrunner.mode') == 'play' and ev(page, 'window.__voidrunner.overlay') is None)
    # ---------------------------------------------------------------- death
    ev(page, "() => { const g = window.__voidrunner.game; g.run.fragments = 25; g.player.hp = 1; g.player.iframes = 0; g.damagePlayer(50, 0, true); }")
    time.sleep(3)
    check('death screen: Wyprawa zakończona', page.get_by_text('Wyprawa zakończona').count() == 1)
    check('death screen buttons', page.get_by_text('Spróbuj ponownie').count() == 1 and page.get_by_text('Powrót do bazy').count() == 1)
    meta = ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1'))")
    check('fragments kept after death (permanent progress)', meta['fragments'] >= 25, str(meta['fragments']))
    check('expedition save cleared after death', ev(page, "localStorage.getItem('voidrunner.run.v1')") is None)
    page.screenshot(path=f'{out}/09-death.png')
    # ---------------------------------------------------------------- base / permanent upgrades
    page.click('text=Powrót do bazy')
    time.sleep(0.5)
    check('base screen opens', page.get_by_text('Trwałe ulepszenia').count() >= 1)
    before = ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).fragments")
    page.click('[data-act=perm][data-id=hp]')
    time.sleep(0.3)
    m2 = ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1'))")
    check('buying Wzmocniony Pancerz', m2['perm'].get('hp') == 1 and m2['fragments'] == before - 15, json.dumps(m2['perm']))
    page.screenshot(path=f'{out}/10-base.png')
    page.click('text=Rozpocznij kolejną wyprawę')
    time.sleep(1.2)
    check('second expedition starts without the tutorial room', ev(page, 'window.__voidrunner.game.room.template') != 'samouczek')
    check('permanent upgrade applies (max HP 115)', ev(page, 'window.__voidrunner.game.player.maxHp') == 115)
    # ---------------------------------------------------------------- continue after reload
    page.keyboard.down('KeyD')
    time.sleep(0.8)
    page.keyboard.up('KeyD')
    check('save point reached in the new expedition', ev(page, "!!localStorage.getItem('voidrunner.run.v1')"))
    page.reload()
    time.sleep(1.2)
    check('Kontynuuj enabled after reload', not page.locator('[data-act=continue]').is_disabled())
    page.click('[data-act=continue]')
    time.sleep(1.0)
    check('Kontynuuj resumes the expedition', ev(page, 'window.__voidrunner.mode') == 'play')
    # ---------------------------------------------------------------- final boss and victory
    ev(page, "() => { const g = window.__voidrunner.game; g.enterRoom(4, 5); g.events.length = 0; }")
    time.sleep(2.4)
    check('final boss fight: boss bar visible', page.locator('.boss-bar').count() == 1)
    page.screenshot(path=f'{out}/11-boss.png')
    ev(page, "() => { const g = window.__voidrunner.game; g.player.iframes = 99; const b = g.boss(); g.killEnemy(b); }")
    time.sleep(1.5)
    ev(page, "() => { const g = window.__voidrunner.game; const e = g.exitRect(); g.player.x = e.x; g.player.y = e.y + e.h - g.player.h - 1; }")
    time.sleep(3.0)
    check('victory screen: Misja zakończona', page.get_by_text('Misja zakończona').count() == 1)
    check('victory: Powrót do bazy', page.get_by_text('Powrót do bazy').count() == 1)
    page.screenshot(path=f'{out}/12-victory.png')
    check('victory recorded', ev(page, "JSON.parse(localStorage.getItem('voidrunner.meta.v1')).stats.wins") == 1)
    ctx.close()

    # ---------------------------------------------------------------- mobile
    m = b.new_context(viewport={'width': 844, 'height': 390}, device_scale_factor=2, is_mobile=True, has_touch=True)
    mp = m.new_page()
    mp.on('pageerror', lambda e: errors.append(f'mobile: {e}'))
    mp.goto(URL)
    time.sleep(1.2)
    mp.locator('[data-act=new]').tap()
    time.sleep(0.6)
    if mp.get_by_text('Zaczynamy').count():
        mp.get_by_text('Zaczynamy').tap()
    time.sleep(1.2)
    check('mobile: touch controls visible', mp.locator('.touch:not([hidden]) button').count() >= 9)
    x0 = mp.evaluate('window.__voidrunner.game.player.x')
    btn = mp.locator('.touch .tr')
    box = btn.bounding_box()
    mp.dispatch_event('.touch .tr', 'pointerdown')
    time.sleep(0.5)
    mp.dispatch_event('.touch .tr', 'pointerup')
    check('mobile: touch button moves the player', mp.evaluate('window.__voidrunner.game.player.x') - x0 > 20)
    mp.screenshot(path=f'{out}/13-mobile.png')
    m.close()
    b.close()

check('no page errors', not errors, '; '.join(errors[:5]))
print(f"\n{sum(ok for _, ok in results)}/{len(results)} checks passed")
sys.exit(0 if all(ok for _, ok in results) else 1)
