"""EVGAMES end-to-end checks in Chromium. Usage: python3 tools/e2e_platform.py <base_url> <screenshot_dir>"""
import json, sys, time
from playwright.sync_api import sync_playwright
base, out = sys.argv[1].rstrip('/'), sys.argv[2]
errors, results = [], []
expect_404 = [False]  # set while a missing game build is simulated on purpose
def check(name, ok, extra=''):
    results.append((name, bool(ok))); print(('PASS ' if ok else 'FAIL ') + name + (f' — {extra}' if extra else ''))

with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    ctx = b.new_context(viewport={'width': 1440, 'height': 900})
    page = ctx.new_page()
    # 3D games render on the CPU here (SwiftShader, no GPU): one frame can take seconds, so screenshots get more time
    page.set_default_timeout(120000)
    page.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    page.on('console', lambda m: errors.append(f'console.{m.type}: {m.text}') if m.type == 'error' and not (expect_404[0] and '404' in m.text) else None)
    page.goto(base + '/'); page.wait_for_selector('.wordmark'); time.sleep(0.8)
    page.screenshot(path=f'{out}/01-home.png')
    page.screenshot(path=f'{out}/01-home-full.png', full_page=True)
    check('home title', page.title() == 'EVGAMES — Browser Games', page.title())
    check('hero has Graj teraz', page.get_by_role('link', name='Graj teraz', exact=True).count() == 1)
    check('library shows all five games', page.locator('#biblioteka .card:not(.soon)').count() == 5)
    lib_txt = ' '.join(page.locator('#biblioteka .card').all_text_contents())
    check('removed games are gone from the library', not any(n in lib_txt for n in ('Popielny Dzwon', 'NIGHT SHIFT', 'BACKROOMS', 'BABCIA')))
    # home search filter (local)
    page.fill('#lib-title-q', 'xyz123'); time.sleep(0.2)
    check('no-results state', page.locator('#biblioteka .empty').count() == 1)
    page.locator('#biblioteka .empty button').click(); time.sleep(0.2)
    check('clear filters restores', page.locator('#biblioteka .card:not(.soon)').count() == 5)
    page.fill('#lib-title-q', 'swietle'); time.sleep(0.2)
    check('diacritic-insensitive search finds Lampiarz', page.locator('#biblioteka .card:not(.soon)').count() == 1)
    page.fill('#lib-title-q', '')
    check('empty categories are disabled (only Horror now)', page.locator('#biblioteka button:disabled').count() == 1)
    check('no 18+ badge left in the library', page.locator('#biblioteka .card .label.age').count() == 0)
    page.get_by_role('button', name='Akcja 3').click(); time.sleep(0.2)
    akcja = ' '.join(page.locator('#biblioteka .card:not(.soon)').all_text_contents())
    check('category filter Akcja shows RANDOM CHAOS, ECHOBOUND and VOIDRUNNER', page.locator('#biblioteka .card:not(.soon)').count() == 3 and 'RANDOM CHAOS' in akcja and 'ECHOBOUND' in akcja and 'VOIDRUNNER' in akcja)
    page.get_by_role('button', name='Puzzle 1').click(); time.sleep(0.2)
    check('category filter Puzzle shows ECHOBOUND', page.locator('#biblioteka .card:not(.soon)').count() == 1 and 'ECHOBOUND' in (page.locator('#biblioteka .card:not(.soon)').first.text_content() or ''))
    page.get_by_role('button', name='Symulacje 1').click(); time.sleep(0.2)
    check('category filter Symulacje shows Skrzynkomat', page.locator('#biblioteka .card:not(.soon)').count() == 1 and 'Skrzynkomat' in (page.locator('#biblioteka .card:not(.soon)').first.text_content() or ''))
    page.get_by_role('button', name='Imprezowe 1').click(); time.sleep(0.2)
    check('category filter Imprezowe shows RANDOM CHAOS', page.locator('#biblioteka .card:not(.soon)').count() == 1 and 'RANDOM CHAOS' in (page.locator('#biblioteka .card:not(.soon)').first.text_content() or ''))
    page.get_by_role('button', name='Strategia 1').click(); time.sleep(0.2)
    check('category filter Strategia', page.locator('#biblioteka .card:not(.soon)').count() == 1)
    page.get_by_role('button', name='Wszystkie 5').click()
    # favourite toggle
    page.locator('#biblioteka .card:has-text("Lampiarz") .fav-btn').first.click(); time.sleep(0.3)
    favs = page.evaluate("localStorage.getItem('evgames.favorites.v1')")
    check('favorite stored', favs == '["lampiarz"]', favs)
    check('nav badge shows 1', page.locator('.nav .badge').inner_text() == '1')
    # header search -> /games?q=
    page.fill('#search-desktop', 'roguelite'); page.keyboard.press('Enter'); time.sleep(0.5)
    check('header search navigates', '/games?q=roguelite' in page.url, page.url)
    check('library result for roguelite (Lampiarz, VOIDRUNNER)', page.locator('.card:not(.soon)').count() == 2)
    page.screenshot(path=f'{out}/02-library.png')
    page.goto(base + '/games?q=zzzz'); time.sleep(0.6)
    check('direct load /games?q= shows empty state', page.locator('.empty').count() == 1)
    page.screenshot(path=f'{out}/03-empty.png')
    # details
    page.goto(base + '/games/lampiarz'); page.wait_for_selector('.detail-hero h1'); time.sleep(0.6)
    check('detail page refresh-safe + title', page.title() == 'Lampiarz — EVGAMES', page.title())
    page.screenshot(path=f'{out}/04-detail.png')
    page.screenshot(path=f'{out}/04-detail-full.png', full_page=True)
    page.locator('.shots button').first.click(); time.sleep(0.3)
    check('lightbox opens', page.locator('.lightbox').count() == 1)
    page.keyboard.press('Escape'); time.sleep(0.2)
    check('lightbox closes on Esc', page.locator('.lightbox').count() == 0)
    # play
    page.get_by_role('link', name='Zagraj teraz').first.click()
    page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 15: time.sleep(0.2)
    check('game started in player', page.locator('.player .state').count() == 0, f'{time.time()-t0:.1f}s')
    check('play url', page.url.endswith('/play/lampiarz'), page.url)
    frame = page.frame_locator('.player iframe')
    time.sleep(1.5)
    page.screenshot(path=f'{out}/05-player-menu.png')
    rec = page.evaluate("JSON.parse(localStorage.getItem('evgames.recent.v1'))")
    check('recently played stored', rec and rec[0]['slug'] == 'lampiarz')
    frame.get_by_role('button', name='Nowa noc').click(); time.sleep(0.4)
    check('first night offers the Lampiarz tutorial', frame.get_by_role('button', name='Od razu do gry').count() == 1)
    frame.get_by_role('button', name='Od razu do gry').click(); time.sleep(0.4)
    frame.get_by_role('button', name='Zapal pierwszą latarnię').click(); time.sleep(0.8)
    frame.get_by_role('button', name='Do roboty').click(); time.sleep(0.3)
    for k in ['ArrowRight', 'ArrowRight', 'ArrowDown', 'Space', 'ArrowUp', 'ArrowLeft']:
        page.keyboard.press(k); time.sleep(0.15)
    time.sleep(0.6)
    run = page.evaluate("JSON.parse(localStorage.getItem('lampiarz.run.v1'))")
    check('keyboard reaches game + save written (same origin)', run and run['district']['turn'] >= 3, f"turn={run and run['district']['turn']}")
    page.screenshot(path=f'{out}/06-player-game.png')
    # focus slipped out of the game (click on the bar title): keys still reach the game
    page.locator('.player .bar .title b').click(); time.sleep(0.2)
    page.evaluate("document.activeElement && document.activeElement.blur && document.activeElement.blur()")
    turn_before = run['district']['turn']
    for k in ['ArrowLeft', 'ArrowRight']:
        page.keyboard.press(k); time.sleep(0.2)
    time.sleep(0.4)
    run2 = page.evaluate("JSON.parse(localStorage.getItem('lampiarz.run.v1'))")
    check('keys pressed outside the frame are forwarded to the game', run2 and run2['district']['turn'] > turn_before, f"{turn_before} -> {run2 and run2['district']['turn']}")
    check('frame gets the focus back', page.evaluate("document.activeElement && document.activeElement.tagName") == 'IFRAME')
    # refresh directly on /play/lampiarz keeps progress
    page.reload(); page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 15: time.sleep(0.2)
    check('refresh on /play works', page.locator('.player .state').count() == 0)
    time.sleep(1)
    check('game offers continue after refresh', frame.get_by_role('button', name='Kontynuuj noc').count() == 1)
    # back navigation
    page.go_back(); time.sleep(0.6)
    check('browser back leaves player', '/play/' not in page.url, page.url)
    page.go_forward(); time.sleep(0.6)
    check('browser forward returns to player', page.url.endswith('/play/lampiarz'))
    page.get_by_role('link', name='Wróć do strony gry').click(); time.sleep(0.5)
    check('player back button -> detail', page.url.endswith('/games/lampiarz'))
    # favourites page
    page.goto(base + '/favorites'); time.sleep(0.6)
    check('favorites page lists game + recent', page.locator('.card').count() == 1 and page.locator('.mini').count() == 1)
    page.screenshot(path=f'{out}/07-favorites.png')
    page.locator('.card .fav-btn').click(); time.sleep(0.3)
    check('remove favorite -> empty state', page.locator('#fav-title').count() == 1 and page.locator('.empty').count() >= 1)
    page.get_by_role('button', name='Wyczyść historię').click(); time.sleep(0.2)
    check('clear history -> empty state', page.locator('.mini').count() == 0)
    # other pages
    for path, sel in [('/discover', '.cat-grid'), ('/new', '.featured'), ('/privacy', '.legal'), ('/nie-ma-takiej', '.notfound'), ('/games/nieistnieje', '.notfound'), ('/play/nieistnieje', '.notfound')]:
        page.goto(base + path); time.sleep(0.5)
        check(f'route {path}', page.locator(sel).count() >= 1)
    page.goto(base + '/discover'); time.sleep(0.4); page.screenshot(path=f'{out}/08-discover.png')
    page.goto(base + '/nie-ma-takiej'); time.sleep(0.4); page.screenshot(path=f'{out}/09-404.png')
    # missing game build -> error state
    expect_404[0] = True
    page.route('**/g/lampiarz/index.html', lambda r: r.fulfill(status=404, body='<!doctype html><title>404: NOT_FOUND</title><h1>This page could not be found</h1>', content_type='text/html'))
    page.goto(base + '/play/lampiarz'); page.wait_for_selector('.player .state[role=alert]', timeout=18000)
    check('missing game build -> error state', page.locator('.player .state[role=alert]').count() == 1)
    page.screenshot(path=f'{out}/10-player-error.png')
    page.unroute('**/g/lampiarz/index.html')
    expect_404[0] = False
    # ---- removed titles: detail and play pages answer with "not found", builds are gone
    for slug in ('popielny-dzwon', 'night-shift', 'backrooms-the-descent', 'babcia'):
        page.goto(base + '/games/' + slug); time.sleep(0.5)
        check(f'{slug}: no detail page any more', page.locator('.detail-hero h1').count() == 0)
        page.goto(base + '/play/' + slug); time.sleep(0.5)
        check(f'{slug}: no player any more', page.locator('.player iframe').count() == 0)
    lamp_before = page.evaluate("localStorage.getItem('lampiarz.profile.v1')")
    # ---- fifth title: RANDOM CHAOS (2 players, one keyboard)
    page.goto(base + '/games/random-chaos'); page.wait_for_selector('.detail-hero h1'); time.sleep(0.6)
    check('RANDOM CHAOS detail page', page.title() == 'RANDOM CHAOS — EVGAMES', page.title())
    check('RANDOM CHAOS detail has 7 screenshots and no 18+ badge', page.locator('.shots img').count() == 7 and page.locator('.detail-hero .pill.age').count() == 0)
    page.screenshot(path=f'{out}/17-rc-detail.png')
    page.goto(base + '/play/random-chaos'); page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 20: time.sleep(0.2)
    check('RANDOM CHAOS started in player', page.locator('.player .state').count() == 0, f'{time.time()-t0:.1f}s')
    rf = page.frame_locator('.player iframe')
    rf.locator('[data-id=play]').wait_for(timeout=30000)
    check('RANDOM CHAOS menu inside iframe', rf.locator('canvas.rc-canvas').count() == 1 and rf.locator('[data-id=tournament]').count() == 1)
    check('RANDOM CHAOS back link leaves the iframe', rf.locator('[data-id=evgames]').get_attribute('target') == '_top')
    rf.locator('[data-id=play]').click(); time.sleep(0.4)
    check('RANDOM CHAOS intro card after GRAJ', rf.locator('.rc-intro').count() == 1)
    rf.locator('[data-id=go]').click(); time.sleep(4.2)
    page.keyboard.down('KeyD'); page.keyboard.down('ArrowLeft'); time.sleep(0.4)
    page.keyboard.up('KeyD'); page.keyboard.up('ArrowLeft')
    check('arrow keys inside the game do not scroll the platform page', page.evaluate('window.scrollY') == 0)
    page.screenshot(path=f'{out}/18-rc-player.png')
    check('RANDOM CHAOS round running inside the player (HUD canvas, no error screen)', rf.locator('[role=alert]').count() == 0 and rf.locator('.rc-intro').count() == 0)
    check('Lampiarz save untouched by RANDOM CHAOS', page.evaluate("localStorage.getItem('lampiarz.profile.v1')") == lamp_before)
    # ---- sixth title: Skrzynkomat (single HTML game by a co-owner, symulacje)
    page.goto(base + '/games/skrzynkomat'); page.wait_for_selector('.detail-hero h1'); time.sleep(0.6)
    check('Skrzynkomat detail page', page.title() == 'Skrzynkomat — EVGAMES', page.title())
    check('Skrzynkomat detail has 8 screenshots and the touch note', page.locator('.shots img').count() == 8 and page.get_by_text('wszystko obsłużysz dotykiem').count() == 1)
    page.screenshot(path=f'{out}/19-sk-detail.png')
    page.goto(base + '/play/skrzynkomat'); page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 20: time.sleep(0.2)
    check('Skrzynkomat started in player', page.locator('.player .state').count() == 0, f'{time.time()-t0:.1f}s')
    sf = page.frame_locator('.player iframe')
    sf.locator('[data-m=play]').click(); time.sleep(0.4)
    sf.locator('[data-open=stal]').click(); time.sleep(1.2)
    sf.locator('#skip').click(); time.sleep(0.8)
    check('Skrzynkomat opens a case inside the player', sf.locator('#result.on').count() == 1)
    page.screenshot(path=f'{out}/20-sk-player.png')
    sf.locator('#rKeep').click(); time.sleep(0.3)
    sk = page.evaluate("localStorage.getItem('skrzynkomat.v1')")
    check('Skrzynkomat saves under its own key', bool(sk) and '"opened":1' in sk)
    # ---- eighth title: ECHOBOUND (2D platformer)
    page.goto(base + '/games/echobound'); page.wait_for_selector('.detail-hero h1'); time.sleep(0.6)
    check('ECHOBOUND detail page', page.title() == 'ECHOBOUND — EVGAMES', page.title())
    check('ECHOBOUND detail has 5 screenshots', page.locator('.shots img').count() == 5)
    page.screenshot(path=f'{out}/23-eb-detail.png')
    page.goto(base + '/play/echobound'); page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 30: time.sleep(0.2)
    check('ECHOBOUND started in player', page.locator('.player .state').count() == 0, f'{time.time()-t0:.1f}s')
    ef = page.frame_locator('.player iframe')
    ef.get_by_text('NOWA GRA').wait_for(timeout=30000)
    check('ECHOBOUND menu inside iframe', ef.locator('canvas').count() >= 1 and ef.get_by_text('KONTYNUUJ').count() == 1)
    page.screenshot(path=f'{out}/24-eb-player.png')
    # ---- VOIDRUNNER (2D action roguelite)
    page.goto(base + '/games/voidrunner'); page.wait_for_selector('.detail-hero h1'); time.sleep(0.6)
    check('VOIDRUNNER detail page', page.title() == 'VOIDRUNNER — EVGAMES', page.title())
    check('VOIDRUNNER detail has 6 screenshots', page.locator('.shots img').count() == 6)
    page.screenshot(path=f'{out}/25-vr-detail.png')
    page.goto(base + '/play/voidrunner'); page.wait_for_selector('.player iframe')
    t0 = time.time()
    while page.locator('.player .state').count() and time.time() - t0 < 30: time.sleep(0.2)
    check('VOIDRUNNER started in player', page.locator('.player .state').count() == 0, f'{time.time()-t0:.1f}s')
    vf = page.frame_locator('.player iframe')
    vf.locator('[data-act=new]').wait_for(timeout=30000)
    check('VOIDRUNNER menu inside iframe', vf.locator('.logo').count() == 1 and vf.locator('[data-act=hub]').count() == 1)
    vf.locator('[data-act=new]').click(); time.sleep(0.6)
    if vf.get_by_text('Zaczynamy').count(): vf.get_by_text('Zaczynamy').click()
    time.sleep(1.2)
    page.keyboard.down('KeyD'); time.sleep(0.4); page.keyboard.press('Space'); page.keyboard.up('KeyD')
    check('arrow/space keys in VOIDRUNNER do not scroll the platform page', page.evaluate('window.scrollY') == 0)
    page.screenshot(path=f'{out}/26-vr-player.png')
    keys = page.evaluate("Object.keys(localStorage)")
    check('no unexpected storage keys', all(k.startswith(('evgames.', 'lampiarz.', 'randomchaos.', 'skrzynkomat.', 'echobound.', 'voidrunner.')) for k in keys), ','.join(keys))
    # keyboard focus visible on nav
    page.goto(base + '/'); time.sleep(0.4)
    page.keyboard.press('Tab'); page.keyboard.press('Tab')
    check('keyboard tab reaches header', page.evaluate("document.activeElement && document.activeElement.closest('header') !== null"))
    ctx.close()

    m = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True)
    mp = m.new_page(); mp.set_default_timeout(120000); mp.on('pageerror', lambda e: errors.append(f'pageerror(m): {e}'))
    mp.goto(base + '/'); mp.wait_for_selector('.wordmark'); time.sleep(0.6)
    mp.screenshot(path=f'{out}/m1-home.png')
    sw = mp.evaluate('document.documentElement.scrollWidth')
    check('mobile no horizontal scroll', sw <= 390, f'scrollWidth={sw}')
    mp.get_by_role('button', name='Otwórz menu').tap(); time.sleep(0.4)
    mp.screenshot(path=f'{out}/m2-menu.png')
    mp.locator('#mobile-nav a.m', has_text='Gry').tap(); time.sleep(0.5)
    check('mobile menu navigates', mp.url.endswith('/games'))
    mp.screenshot(path=f'{out}/m3-library.png', full_page=True)
    mp.goto(base + '/games/lampiarz'); time.sleep(0.6)
    sw = mp.evaluate('document.documentElement.scrollWidth')
    check('mobile detail no h-scroll', sw <= 390, f'scrollWidth={sw}')
    mp.screenshot(path=f'{out}/m4-detail.png', full_page=True)
    mp.goto(base + '/play/random-chaos'); time.sleep(2)
    coarse = mp.evaluate("matchMedia('(hover: none) and (pointer: coarse)').matches")
    n_note = mp.locator('.player [role=note]').count()
    # the note must appear exactly when the browser reports a touch-only device
    check('RANDOM CHAOS touch notice matches the device', n_note == (1 if coarse else 0), f'coarse={coarse} notes={n_note}')
    mp.screenshot(path=f'{out}/m6-rc-player.png')
    mp.goto(base + '/play/lampiarz'); time.sleep(3)
    check('mobile player starts', mp.locator('.player .state').count() == 0)
    mp.screenshot(path=f'{out}/m5-player.png')
    m.close(); b.close()

print(f"\n{sum(ok for _, ok in results)}/{len(results)} checks passed")
print('ERRORS:', json.dumps(errors, ensure_ascii=False, indent=1) if errors else 'none')
